function productUrlLocale(value) {
  const key = String(value || "").toLowerCase();
  return Object.hasOwn(URL_LOCALES, key) ? URL_LOCALES[key] : "";
}

const PREFERRED_LOCALE_KEY = "mySpellingGamePreferredLocale";

export function rememberProductLocale(locale) {
  const normalized = normalizeProductLocale(locale);
  try {
    localStorage.setItem(PREFERRED_LOCALE_KEY, normalized);
  } catch {}
  return normalized;
}

export function normalizeProductLocale(value) {
  const raw = String(value || "en").toLowerCase();
  return (
    ALIASES[raw] ||
    (PACKS[raw]
      ? raw
      : raw.startsWith("pt")
        ? "pt-BR"
        : raw.startsWith("zh")
          ? "zh"
          : "en")
  );
}

export function productPagePath(page = "", locale = productLocale()) {
  const normalized = normalizeProductLocale(locale);
  const directory =
    normalized === "en" ? "" : normalized === "pt-BR" ? "pt-br" : normalized;
  const suffix = page ? `/${String(page).replace(/^\/+/, "")}` : "/";
  return directory ? `/${directory}${suffix}` : suffix;
}

export function productLocale() {
  const params = new URLSearchParams(location.search);
  const query = params.get("lang");
  const path = location.pathname.split("/")[1];
  let pending = "";
  let stored = "";
  if (params.get("checkout") === "success") {
    try {
      pending = sessionStorage.getItem(PENDING_CHECKOUT_LOCALE_KEY) || "";
    } catch {}
  }
  try {
    stored = localStorage.getItem(PREFERRED_LOCALE_KEY) || "";
  } catch {}
  const pendingLocale = productUrlLocale(pending);
  const queryLocale = productUrlLocale(query);
  const storedLocale = productUrlLocale(stored);
  const pathLocale = path === "en" ? "" : productUrlLocale(path);
  if (queryLocale) rememberProductLocale(queryLocale);
  return normalizeProductLocale(
    pendingLocale ||
      queryLocale ||
      storedLocale ||
      pathLocale ||
      navigator.languages?.[0] ||
      navigator.language,
  );
}

export function productMessages(locale = productLocale()) {
  return {
    ...(PACKS[locale] || PACKS.en),
    ...(SENTENCE_LIBRARY_COPY[locale] || SENTENCE_LIBRARY_COPY.en),
    ...(TODAYS_REVIEW_COPY[locale] || TODAYS_REVIEW_COPY.en),
  };
}

export function productMessage(key, vars = {}, locale = productLocale()) {
  const pack = productMessages(locale);
  return String(pack[key] ?? PACKS.en[key] ?? key).replace(
    /\{(\w+)\}/g,
    (_, name) => String(vars[name] ?? ""),
  );
}

export function setProductLocale(locale) {
  const normalized = rememberProductLocale(locale);
  const url = new URL(location.href);
  url.searchParams.set("lang", normalized);
  location.href = url.toString();
}

if (typeof document !== "undefined") {
  document.addEventListener("click", (event) => {
    const link = event.target.closest?.("a.lang-option[hreflang]");
    if (link) rememberProductLocale(link.getAttribute("hreflang"));
  });
}


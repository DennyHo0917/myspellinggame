const ALIASES = {
  "pt-br": "pt-BR",
  pt_br: "pt-BR",
  "zh-cn": "zh",
  "zh-hans": "zh",
};

export function normalizeProductLocale(value) {
  const raw = String(value || "en").toLowerCase();
  return (
    ALIASES[raw] ||
    (PACKS[raw]
      ? raw
      : raw.startsWith("pt")
        ? "pt-BR"
        : raw.startsWith("zh")
          ? "zh"
          : "en")
  );
}

export function productPagePath(page = "", locale = productLocale()) {
  const normalized = normalizeProductLocale(locale);
  const directory =
    normalized === "en" ? "" : normalized === "pt-BR" ? "pt-br" : normalized;
  const suffix = page ? `/${String(page).replace(/^\/+/, "")}` : "/";
  return directory ? `/${directory}${suffix}` : suffix;
}

export function productLocale() {
  const query = new URLSearchParams(location.search).get("lang");
  const path = location.pathname.split("/")[1];
  let stored = "";
  try {
    stored = localStorage.getItem("mySpellingGamePreferredLocale") || "";
  } catch {}
  const pathLocale = normalizeProductLocale(path);
  return normalizeProductLocale(
    query ||
      (PACKS[pathLocale] ? pathLocale : "") ||
      stored ||
      navigator.language,
  );
}

export function productMessages(locale = productLocale()) {
  return PACKS[locale] || PACKS.en;
}

export function productMessage(key, vars = {}, locale = productLocale()) {
  const pack = productMessages(locale);
  return String(pack[key] ?? PACKS.en[key] ?? key).replace(
    /\{(\w+)\}/g,
    (_, name) => String(vars[name] ?? ""),
  );
}

export function setProductLocale(locale) {
  const normalized = normalizeProductLocale(locale);
  try {
    localStorage.setItem("mySpellingGamePreferredLocale", normalized);
  } catch {}
  const url = new URL(location.href);
  url.searchParams.set("lang", normalized);
  location.href = url.toString();
}

